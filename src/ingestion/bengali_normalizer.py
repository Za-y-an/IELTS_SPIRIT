def normalize_bengali_text(text: str) -> Tuple[str, NormalizationReport]:
    """
    Apply grounded Bengali glyph normalization to extracted document text.
    Preserves all numbers, prices, English terms, and layout delimiters.
    Rules are processed strictly by pattern length descending so that full phrases
    and compound tokens are resolved before individual sub-tokens.
    Returns the normalized string and a detailed NormalizationReport.
    """
    original_chars = len(text)
    normalized = text
    rules_applied: Dict[str, int] = {}
    total_replacements = 0

    # Sort rules strictly by length descending (longest phrases first)
    sorted_corruptions = sorted(OBSERVED_CORRUPTIONS, key=lambda x: len(x[0]), reverse=True)

    for pattern, replacement, desc in sorted_corruptions:
        if pattern in normalized:
            count = normalized.count(pattern)
            normalized = normalized.replace(pattern, replacement)
            total_replacements += count
            rules_applied[f"{pattern} -> {replacement} ({desc})"] = count

    # Normalize digit counters: e.g. ২০টট -> ২০টি, ১টট -> ১টি, 5টট -> 5টি
    digit_counter_pattern = re.compile(r'([০-৯\d]+)টট\b')
    counter_matches = list(digit_counter_pattern.finditer(normalized))
    if counter_matches:
        count = len(counter_matches)
        normalized = digit_counter_pattern.sub(r'\g<1>টি', normalized)
        total_replacements += count
        rules_applied["[০-৯\\d]+টট -> [০-৯\\d]+টি (Digit counter)"] = count

    # Clean up double spaces that may arise around punctuation
    normalized = re.sub(r"[ \t]+", " ", normalized)
    # Ensure proper spacing around newline-preserved structures
    normalized = re.sub(r"\n{3,}", "\n\n", normalized)



    report = NormalizationReport(
        original_char_count=original_chars,
        normalized_char_count=len(normalized),
        total_replacements=total_replacements,
        rules_applied=rules_applied,
    )
    return normalized, report


def normalize_extracted_pages(pages: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], NormalizationReport]:
    """
    Run page-by-page text normalization preserving page metadata (page number, source).
    """
    normalized_pages: List[Dict[str, Any]] = []
    combined_original_chars = 0
    combined_normalized_chars = 0
    total_replacements = 0
    aggregated_rules: Dict[str, int] = {}

    for page in pages:
        raw_text = page.get("text", "")
        norm_text, report = normalize_bengali_text(raw_text)
        normalized_pages.append({
            "page": page.get("page", 1),
            "text": norm_text,
            "source": page.get("source", "unknown.pdf"),
        })
        combined_original_chars += report.original_char_count
        combined_normalized_chars += report.normalized_char_count
        total_replacements += report.total_replacements
        for rule, cnt in report.rules_applied.items():
            aggregated_rules[rule] = aggregated_rules.get(rule, 0) + cnt

    total_report = NormalizationReport(
        original_char_count=combined_original_chars,
        normalized_char_count=combined_normalized_chars,
        total_replacements=total_replacements,
        rules_applied=aggregated_rules,
    )
    return normalized_pages, total_report
