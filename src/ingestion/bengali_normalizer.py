"""
Bengali text normalizer for IELTS Spirit document extraction.

Addresses systemic font CMap corruption from legacy PDF exports (e.g. Nirmala UI / Bijoy
keyboard encoding mismatches where glyphs like 'কোর্স' extracted as 'জোে স' / 'ককাস ব',
'কত' as 'েত', 'অফলাইন' as 'অফিাইন', etc.).

Every rule in this module is grounded in observed extraction artifacts from ielts.pdf.
Numbers, prices, English text, URLs, phone numbers, and punctuation are strictly preserved.
"""

from dataclasses import dataclass, field
import re
from typing import Any, Dict, List, Optional, Tuple


@dataclass
class NormalizationReport:
    """Detailed telemetry and audit report for text normalization pass."""
    original_char_count: int
    normalized_char_count: int
    total_replacements: int
    rules_applied: Dict[str, int] = field(default_factory=dict)

    def summary(self) -> str:
        top_rules = sorted(self.rules_applied.items(), key=lambda x: x[1], reverse=True)[:10]
        rule_lines = "\n".join([f"    • {rule}: {cnt} replacement(s)" for rule, cnt in top_rules])
        return (
            f"Original Characters:   {self.original_char_count}\n"
            f"Normalized Characters: {self.normalized_char_count}\n"
            f"Total Replacements:    {self.total_replacements}\n"
            f"Distinct Rules Used:   {len(self.rules_applied)}\n"
            f"Top Replacements:\n{rule_lines}"
        )


